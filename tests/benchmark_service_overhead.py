#!/usr/bin/env python3
"""Compare actual PID checks from two trusted controller versions on this host.

Not a VPN throughput benchmark and not a router RAM measurement.
Usage: python3 tests/benchmark_service_overhead.py OLD_SERVICE NEW_SERVICE
"""
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import time


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    results={}
    pid=os.getpid()
    stamp=Path(f'/proc/{pid}/stat').read_text().rsplit(') ',1)[1].split()[19]
    boot=Path('/proc/sys/kernel/random/boot_id').read_text().strip()
    with tempfile.TemporaryDirectory() as tmp:
        root=Path(tmp)
        (root/'pid').write_text(f'{pid} {stamp} {boot}\n')
        for label, source in zip(['before','after'], sys.argv[1:]):
            source=Path(source).read_text()
            functions='proc_start() {'+source.split('proc_start() {',1)[1].split('\ntrim_logs()',1)[0]
            script=root/(label+'.sh')
            script.write_text(functions+'\nCURRENT_BOOT=; i=0; while [ "$i" -lt 120 ]; do alive "$1" || exit 1; i=$((i+1)); done\n')
            durations=[]
            for _ in range(3):
                started=time.monotonic()
                subprocess.run(['sh',str(script),str(root/'pid')],check=True)
                durations.append(round(time.monotonic()-started,6))
            bindir=root/(label+'-bin');bindir.mkdir()
            trace=root/(label+'.trace')
            for tool in ['cat','awk']:
                # Paths are generated by tempfile and command discovery, never network input.
                wrapper=bindir/tool
                wrapper.write_text(f'#!/bin/sh\nprintf "{tool}\\n" >> "{trace}"\nexec "{shutil.which(tool)}" "$@"\n')
                wrapper.chmod(0o700)
            subprocess.run(['sh',str(script),str(root/'pid')],env={**os.environ,'PATH':str(bindir)+':'+os.environ['PATH']},check=True)
            calls=trace.read_text().splitlines()
            results[label]={'secondsFor120Checks':durations,'helperLaunches':len(calls),'awk':calls.count('awk'),'cat':calls.count('cat')}
    print(json.dumps(results,indent=2))


if __name__=='__main__':
    main()
